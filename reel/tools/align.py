script = open(os.path.join(os.path.dirname(__file__), "script.txt"), encoding="utf-8-sig").read()
pool = script.split()  # the original words, exact code points
import unicodedata
words = []
for si, (a, b, text) in enumerate(SEG):
    n = len(text.split(" "))
    ws, pool = pool[:n], pool[n:]
    assert [unicodedata.normalize("NFC", w) for w in ws] == unicodedata.normalize("NFC", text).split(" "), (si, ws)
    weights = [len(w.strip(",।")) + 1.5 for w in ws]
    tot = sum(weights); t = a
    for w, wt in zip(ws, weights):
        d = (b - a) * wt / tot
        words.append({"id": f"w{len(words)}", "text": w, "start": round(t, 3), "end": round(t + d, 3), "seg": si})
        t += d
assert not pool
assert " ".join(script.split()) == " ".join(w["text"] for w in words), "script mismatch"
json.dump(words, open(os.path.join(os.path.dirname(__file__), "..", "assets", "transcript.json"), "w"), ensure_ascii=False, indent=1)
print(len(words), "words, verbatim OK")
